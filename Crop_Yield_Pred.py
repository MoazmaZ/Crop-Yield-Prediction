# ===== 2. LOAD =====
yield_df = pd.read_csv("faostat_yield.csv")
nasa_df = pd.read_csv("nasa_climate.csv", skiprows=14)
extreme_df = pd.read_csv("worldbank_extremes.csv", encoding="latin1")

# ===== 3. CLEAN YIELD =====
yield_df = yield_df[["Area", "Year", "Item", "Value"]]
yield_df.rename(columns={
    "Item": "Crop",
    "Value": "Yield"
}, inplace=True)

# Keep only selected countries (important for consistency)
countries = ["India", "Pakistan", "Palestine"]
yield_df = yield_df[yield_df["Area"].isin(countries)]

yield_df["Year"] = pd.to_numeric(yield_df["Year"], errors="coerce")
yield_df = yield_df.dropna(subset=["Year"])
yield_df["Year"] = yield_df["Year"].astype(int)

# ===== 4. CLEAN CLIMATE (NASA) =====
nasa_df.columns = ["YEAR", "DOY", "T2M", "T2M_MIN", "T2M_MAX", "PRECTOT"]

nasa_df["YEAR"] = pd.to_numeric(nasa_df["YEAR"], errors="coerce")
nasa_df = nasa_df.dropna(subset=["YEAR"])
nasa_df["YEAR"] = nasa_df["YEAR"].astype(int)

# Aggregate yearly
climate_yearly = nasa_df.groupby("YEAR").agg({
    "T2M": "mean",
    "T2M_MAX": "mean",
    "T2M_MIN": "mean",
    "PRECTOT": "sum"
}).reset_index()

climate_yearly.rename(columns={
    "YEAR": "Year",
    "T2M": "Avg_Temp",
    "T2M_MAX": "Max_Temp",
    "T2M_MIN": "Min_Temp",
    "PRECTOT": "Total_Rainfall"
}, inplace=True)

# ⚠️ Duplicate climate for each country (transparent assumption)
climate_expanded = pd.concat(
    [climate_yearly.assign(Area=country) for country in countries],
    ignore_index=True
)


# ===== 5. CLEAN EXTREME DATA (FINAL FIX) =====

print("Columns:", extreme_df.columns)

# Step 1: get original column name FIRST
year_col_name = extreme_df.columns[2]   # e.g. '1995-07'

# Extract year
year_value = int(year_col_name.split("-")[0])

# Step 2: rename AFTER extraction
extreme_df = extreme_df.rename(columns={
    "code": "Area_Code",
    "name": "Area",
    year_col_name: "Extreme_Rain"
})

# Step 3: add Year column
extreme_df["Year"] = year_value

# Step 4: clean
extreme_df["Extreme_Rain"] = pd.to_numeric(extreme_df["Extreme_Rain"], errors="coerce")

# Step 5: filter countries
countries = ["India", "Pakistan", "Palestine"]
extreme_df = extreme_df[extreme_df["Area"].isin(countries)]

# Step 6: final format
extreme_yearly = extreme_df[["Area", "Year", "Extreme_Rain"]]

print("✅ Extreme data cleaned")
print(extreme_yearly.head())





# ===== 6. MERGE =====

# Merge climate normally (Area + Year)
df = yield_df.merge(climate_expanded, on=["Area", "Year"], how="left")

# 🔥 Merge extreme rainfall as STATIC feature (only on Area)
extreme_yearly["Year"] = extreme_yearly["Year"].astype(int)

df = df.merge(
    extreme_yearly.drop(columns=["Year"]),  # remove Year
    on="Area",
    how="left"
)

# ===== 7. FEATURE ENGINEERING =====
df["Temp_Range"] = df["Max_Temp"] - df["Min_Temp"]

# ===== 8. HANDLE MISSING =====
df = df.dropna(subset=["Yield"])

for col in ["Avg_Temp", "Max_Temp", "Min_Temp", "Total_Rainfall", "Temp_Range"]:
    df[col] = df[col].fillna(df.groupby("Area")[col].transform("mean"))

df["Extreme_Rain"] = df["Extreme_Rain"].fillna(0)

# ===== 9. REMOVE OUTLIERS =====
if len(df) > 50:
    q1 = df["Yield"].quantile(0.01)
    q3 = df["Yield"].quantile(0.99)
    df = df[(df["Yield"] >= q1) & (df["Yield"] <= q3)]

# ===== 10. FINAL CLEAN =====
df = df.drop_duplicates()

# ===== 11. SAVE =====
df.to_csv("final_dataset.csv", index=False)

print("✅ FINAL DATASET READY")
print("Shape:", df.shape)
print(df.head())
print("\nMissing values:\n", df.isnull().sum())

import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from xgboost import XGBRegressor
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense
import matplotlib.pyplot as plt
import seaborn as sns


np.random.seed(42)


df = pd.read_csv("final_dataset.csv")

df = pd.get_dummies(df, columns=["Area"], drop_first=True)

# ==========================
# 3. SPLIT DATA
# ==========================
train = df[df['Year'] <= 2015]
test  = df[df['Year'] > 2015]

X_train = train.drop(["Yield", "Year"], axis=1)
y_train = train["Yield"]

X_test = test.drop(["Yield", "Year"], axis=1)
y_test = test["Yield"]

# ==========================
# 4. SCALE FEATURES
# ==========================
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# ==========================
# 5. TRAIN MODELS
# ==========================
# Linear Regression
lr = LinearRegression()
lr.fit(X_train_scaled, y_train)
lr_pred = lr.predict(X_test_scaled)

# Random Forest
rf = RandomForestRegressor(n_estimators=200, max_depth=10, random_state=42)
rf.fit(X_train, y_train)
rf_pred = rf.predict(X_test)

# XGBoost
xgb = XGBRegressor(n_estimators=200, learning_rate=0.05, max_depth=6, random_state=42)
xgb.fit(X_train, y_train)
xgb_pred = xgb.predict(X_test)

# Neural Network
nn = Sequential()
nn.add(Dense(64, activation='relu', input_shape=(X_train_scaled.shape[1],)))
nn.add(Dense(32, activation='relu'))
nn.add(Dense(1))
nn.compile(optimizer='adam', loss='mse')
nn.fit(X_train_scaled, y_train, validation_split=0.2, epochs=50, batch_size=16, verbose=0)
nn_pred = nn.predict(X_test_scaled).flatten()

# ==========================
# 6. EVALUATE MODELS
# ==========================
def metrics(y_true, y_pred):
    return mean_absolute_error(y_true, y_pred), np.sqrt(mean_squared_error(y_true, y_pred)), r2_score(y_true, y_pred)

results = pd.DataFrame({
    "Model": ["Linear Regression", "Random Forest", "XGBoost", "Neural Network"],
    "MAE": [*metrics(y_test, lr_pred)[:1], *metrics(y_test, rf_pred)[:1], *metrics(y_test, xgb_pred)[:1], *metrics(y_test, nn_pred)[:1]],
    "RMSE": [*metrics(y_test, lr_pred)[1:2], *metrics(y_test, rf_pred)[1:2], *metrics(y_test, xgb_pred)[1:2], *metrics(y_test, nn_pred)[1:2]],
    "R²": [*metrics(y_test, lr_pred)[2:], *metrics(y_test, rf_pred)[2:], *metrics(y_test, xgb_pred)[2:], *metrics(y_test, nn_pred)[2:]]
})

print(results)

# ==========================
# 6. PLOTS (LINEAR REGRESSION ONLY)
# ==========================

# --- (1) Predicted vs Actual ---
plt.figure(figsize=(7,5))
plt.scatter(y_test, lr_pred, alpha=0.6)
plt.xlabel("Actual Yield")
plt.ylabel("Predicted Yield")
plt.title("Linear Regression: Predicted vs Actual")

# perfect prediction line
plt.plot([y_test.min(), y_test.max()],
         [y_test.min(), y_test.max()],
         'r--')

plt.show()

# --- (2) Error Distribution ---
errors = y_test - lr_pred

plt.figure(figsize=(7,5))
sns.histplot(errors, kde=True)
plt.title("Linear Regression Error Distribution")
plt.xlabel("Prediction Error")
plt.show()


