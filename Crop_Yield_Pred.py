        y_sub   = y_tr[:n]
        mdl.fit(Xtr_sub, y_sub)
        tr_maes.append(mean_absolute_error(y_sub, mdl.predict(Xtr_sub)))
        te_maes.append(mean_absolute_error(y_te,  mdl.predict(Xte_full)))

